#!/usr/bin/env node

/**
 * Pack the storage and display kind Autodesk declares for each built-in
 * parameter into `lib/reviter/parameter-specs.data.ts`.
 *
 * The source is `docs/generated/revit-parameter-descriptors.json`, written by
 * `extract-revit-enum-tables.mjs`: one row per parameter with its storage type
 * (`Double`, `Integer`, `String`, `ElementId`), its spec
 * (`autodesk.spec.aec:length`, `autodesk.spec:spec.bool`, ...) and the label
 * Revit shows, which is null for the parameters Revit never shows.
 *
 * Usage:
 *   node scripts/generate-parameter-specs.mjs
 */

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const INPUT = resolve("docs/generated/revit-parameter-descriptors.json");
const OUTPUT = resolve("lib/reviter/parameter-specs.data.ts");

/** Double specs whose internal unit is the foot. */
const LENGTH_SPECS = new Set([
  "autodesk.spec.aec:length",
  "autodesk.spec.aec:sheetLength",
  "autodesk.spec.aec.structural:reinforcementLength",
  "autodesk.spec.aec.structural:sectionDimension",
  "autodesk.spec.aec.structural:reinforcementSpacing",
  "autodesk.spec.aec.structural:barDiameter",
  "autodesk.spec.aec.structural:reinforcementCover",
  "autodesk.spec.aec.hvac:ductSize",
  "autodesk.spec.aec.hvac:ductInsulationThickness",
  "autodesk.spec.aec.hvac:ductLiningThickness",
  "autodesk.spec.aec.electrical:cableTraySize",
  "autodesk.spec.aec.electrical:conduitSize",
  "autodesk.spec.aec.piping:pipeDimension",
  "autodesk.spec.aec.piping:pipeSize",
  "autodesk.spec.aec.piping:pipeInsulationThickness",
  "autodesk.spec.aec.infrastructure:stationing",
  "autodesk.spec.aec.infrastructure:stationingInterval",
]);
const ANGLE_SPECS = new Set(["autodesk.spec.aec:angle", "autodesk.spec.aec:siteAngle"]);
const AREA_SPECS = new Set(["autodesk.spec.aec:area"]);
const VOLUME_SPECS = new Set(["autodesk.spec.aec:volume", "autodesk.spec.aec.piping:volume"]);
const NUMBER_SPECS = new Set(["autodesk.spec.aec:number", "autodesk.spec:spec.string"]);

function kindOf({ storage, spec }) {
  if (storage === "Integer") return spec === "autodesk.spec:spec.bool" ? "bool" : "integer";
  if (storage === "String") return "text";
  if (storage === "ElementId") return "elementId";
  if (storage !== "Double") return "none";
  if (LENGTH_SPECS.has(spec)) return "length";
  if (ANGLE_SPECS.has(spec)) return "angle";
  if (AREA_SPECS.has(spec)) return "area";
  if (VOLUME_SPECS.has(spec)) return "volume";
  if (NUMBER_SPECS.has(spec)) return "number";
  return "measure";
}

const { parameters } = JSON.parse(await readFile(INPUT, "utf8"));
const byKind = new Map();
const hidden = [];
for (const row of parameters) {
  if (!Number.isInteger(row.id) || row.id >= 0) throw new Error(`unexpected parameter id ${row.id}`);
  const kind = kindOf(row);
  if (!byKind.has(kind)) byKind.set(kind, []);
  byKind.get(kind).push(-row.id);
  if (row.label == null) hidden.push(-row.id);
}
const pack = (ids) => ids.sort((a, b) => a - b).map((id) => id.toString(36)).join(",");
const kinds = [...byKind.keys()].sort();
const lines = [
  "// Generated by scripts/generate-parameter-specs.mjs from",
  "// docs/generated/revit-parameter-descriptors.json. Do not edit by hand.",
  "//",
  "// Each list holds the magnitudes of the parameter ids of one kind, in base 36.",
  "",
  "export const PACKED_PARAMETER_KINDS = {",
  ...kinds.map((kind) => `  ${kind}: "${pack(byKind.get(kind))}",`),
  "} as const;",
  "",
  "/** Parameters Revit never shows: the descriptor carries no label. */",
  `export const PACKED_UNLABELLED_PARAMETERS = "${pack(hidden)}";`,
  "",
];
await writeFile(OUTPUT, lines.join("\n"));
console.log(`wrote ${OUTPUT}: ${parameters.length} parameters, ${hidden.length} unlabelled`);
